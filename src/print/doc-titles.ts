/**
 * Представления видов документов, как их печатает 1С:Бухгалтерия для Казахстана (синоним документа): строка
 * «Товарно-транспортная накладная» счёта-фактуры, колонка «Документ» акта сверки. «Реализация ТМЗ и услуг» сверена
 * с печатными формами; для остальных видов — имя объекта по словам («ПлатежноеПоручениеВходящее» → «Платежное
 * поручение входящее»), а там, где синоним 1С короче, — он.
 */
const TITLES: Record<string, string> = {
  Document_РеализацияТоваровУслуг: "Реализация ТМЗ и услуг",
  Document_ПоступлениеТоваровУслуг: "Поступление ТМЗ и услуг",
  Document_ВозвратТоваровОтПокупателя: "Возврат ТМЗ от покупателя",
  Document_ВозвратТоваровПоставщику: "Возврат ТМЗ поставщику",
  Document_АктОбОказанииПроизводственныхУслуг: "Акт об оказании производственных услуг",
  Document_РеализацияУслугПоПереработке: "Реализация услуг по переработке",
};

export function documentTitle(entitySet: string): string {
  const set = entitySet.replace(/^StandardODATA\./, "");
  const known = TITLES[set];
  if (known) return known;
  const words = set.replace(/^Document_/, "").split(/(?=[А-ЯЁA-Z])/);
  return words.map((w, i) => (i ? w.toLowerCase() : w)).join(" ");
}

/** Номер документа без ведущих нулей: «00000000019» → «19». */
export const trimNumber = (n: string): string => n.trim().replace(/^0+(?=\d)/, "");
