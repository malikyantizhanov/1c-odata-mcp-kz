export interface KzFlowDoc {
  entitySet: string;
  block: KzBlock;
  title: string;
  /** Типовая схема проводок (Типовой план счетов РК). */
  postings: string;
  /** Нормы: статья и ссылка. */
  legal: string[];
  /** Ожидаемые счета после проведения: должна быть хотя бы одна проводка с Дт (Кт) из списка (префиксы кодов). */
  expect?: { debit?: string[]; credit?: string[] };
  /** Документ не делает бухгалтерских проводок (регистры НДС, кадров, взаиморасчётов) — 0 проводок норма. */
  noPostings?: boolean;
  /** Особенности заполнения через OData. */
  hints?: string[];
  /** Допустимые значения перечислений шапки (в $metadata 1С их нет — значения сняты с живой базы). */
  enums?: Record<string, string[]>;
  /** Подсказка, если 1С не провела документ без текста ошибки (проверенные причины). */
  postFailureHint?: string;
}

